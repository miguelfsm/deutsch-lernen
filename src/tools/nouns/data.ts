  // translation. Required: the backfill is complete, so the compiler now forces
  // every noun to carry both.
  example: string
  translation: string
  // Lessons this noun belongs to. Every existing noun predates lesson tagging,
  // so all are backfilled to the A1.1 bucket (decision D3).
  lessons: LessonId[]
